function fromRow([cca3, en, de, totalMinutes, servings, diet, allergens]: CuisineRow): CountryCuisine {
  const country = getCountryByCca3(cca3);
  if (!country) throw new Error(`Unknown cuisine country ${cca3}`);
  const blurb = COUNTRY_DISH_BLURBS[cca3];
  if (!blurb) throw new Error(`Missing dish blurb for ${cca3}`);
  return {
    cca3,
    dish: { en, de },
    blurb,
    totalMinutes,
    servings,
    diet,
    allergens: [...allergens],
  };
}

export const COUNTRY_CUISINES: Record<string, CountryCuisine> = Object.fromEntries(
  rows.map((row) => [row[0], fromRow(row)])
);

export function getCountryCuisine(cca3: string): CountryCuisine | null {
  return COUNTRY_CUISINES[cca3] ?? null;
}
